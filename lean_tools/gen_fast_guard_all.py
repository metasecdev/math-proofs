#!/usr/bin/env python3
"""Driver: compute guard depths for n in [A,B) (cached in JSON) and write modules
Thoughts/Proved/BBPFastCerts<B>Part<i>.lean (100 n each) + aggregator BBPFastCerts<B>.lean.
usage: gen_fast_guard_all.py A B PROCS"""
import sys, json, os
from multiprocessing import Pool
sys.path.insert(0, os.path.dirname(__file__))
import gen_fast_guard as G
CH = int(os.environ.get('CH', '100'))
def work(n): return G.gof(n)
def write_modules(A, B, gs):
    tag = f"BBPFastCerts{B-1}" if A == 0 else f"BBPFastCertsT{A}to{B-1}"
    cmd = f"lean_tools/gen_fast_guard_all.py {A} {B} 3"
    starts = list(range(A, B, CH))
    for i, a in enumerate(starts):
        b = min(a + CH, B)
        src = G.gen_part(a, b, 'x', '', cmd, gs[a - A:b - A]).replace("namespace FinitistProved", "set_option maxHeartbeats 0\nnamespace FinitistProved", 1)
        src = src.replace("private theorem fast_chunk", f"private theorem fast_chunk_{a}").replace("fast_chunk (n", f"fast_chunk_{a} (n").replace(" fast_chunk ", f" fast_chunk_{a} ")
        # use the cached g's rather than recomputing
        gl = ", ".join(str(g) for g in gs[a - A:b - A])
        import re
        src = re.sub(r"chkFrom (\d+) \[[^\]]*\]", lambda m: f"chkFrom {m.group(1)} [{gl}]", src)
        open(f"Thoughts/Proved/{tag}Part{i}.lean", "w").write(src)
    # aggregator
    L = [f"/-\n  GENERATED by `{cmd}`; do not edit.\n\n  {('`bbpGuardAgrees_of_lt_%d` : `∀ n < %d, bbpGuardAgrees n`.' % (B,B)) if A==0 else ('`bbpGuardAgrees_Ico_%d_%d` : `∀ n, %d ≤ n → n < %d → bbpGuardAgrees n`.' % (A,B,A,B))}\n  every n in [{A}, {B}) is checked by the `{tag}Part*` modules (residue-form check, `BBPFastGuard.lean`).\n-/",
         ]
    for i in range(len(starts)): L.append(f"import Thoughts.Proved.{tag}Part{i}")
    if A == 0:
        L += ["", "namespace FinitistProved", "", f"theorem bbpGuardAgrees_of_lt_{B} : ∀ n < {B}, bbpGuardAgrees n := by", "  intro n hn"]
    else:
        L += ["", "namespace FinitistProved", "", f"theorem bbpGuardAgrees_Ico_{A}_{B} : ∀ n, {A} ≤ n → n < {B} → bbpGuardAgrees n := by", "  intro n hA hn"]
    for i, a in enumerate(starts):
        b = min(a + CH, B)
        L += [f"  by_cases h{i} : n < {b}", f"  · exact bbpGuardAgrees_range_{a}_{b} n (by omega) h{i}"]
    L += ["  omega", "", "end FinitistProved", ""]
    open(f"Thoughts/Proved/{tag}.lean", "w").write("\n".join(L))

if __name__ == "__main__":
    A, B, P = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3])
    cache = f"/workspace/fast_g_{A}_{B}.json"
    full = "/workspace/fast_g_0_10001.json"
    if not os.path.exists(cache) and os.path.exists(full) and B <= 10001:
        json.dump(json.load(open(full))[A:B], open(cache, "w"))
    if os.path.exists(cache):
        gs = json.load(open(cache))
    else:
        with Pool(P) as pool:
            gs = pool.map(work, range(A, B), chunksize=8)
        json.dump(gs, open(cache, "w"))
    write_modules(A, B, gs)
    print("done", A, B, "max g", max(g for g in gs if g), "fails", [A + i for i, g in enumerate(gs) if g is None])
