"""Generate a Lean module checking `chkFrom A [g_A, g_{A+1}, ...]` by `decide +kernel`
(Thoughts/Proved/BBPFastGuard.lean). g_n is the first g in {4,..,64} with E<=s and s+E<16^g,
s = S mod 16^g computed with the same residue formulas (small numbers, Python pow(...,mod)).
usage: gen_fast_guard.py A B  -> prints g-list for n in [A,B)"""
import sys
def termmod(k,N,M):
    if k>N: return 0
    m=N-k
    r=0
    def a(c,d):
        dm=d*M
        return ((c*pow(16,m,dm))%dm)//d
    return (a(4,8*k+1)+3*M-(a(2,8*k+4)+a(1,8*k+5)+a(1,8*k+6)))%M
def gof(n):
    for g in range(4,65,4):
        N=n+g; M=16**g
        s=sum(termmod(k,N,M) for k in range(N+1))%M
        E=4*(n+g+1)+2
        if E<=s and s+E<M: return g
    return None
if __name__=="__main__":
    A,B=int(sys.argv[1]),int(sys.argv[2])
    print([gof(n) for n in range(A,B)])

# ---- Lean module generation --------------------------------------------------------------
