#!/usr/bin/env python3
"""Aggregate the first K verified parts of BBPFastCerts10000Part* (parts cover [100i, 100i+100)) into
BBPFastCerts<bound-1>.lean proving `bbpGuardAgrees_of_lt_<bound>` (bound = 100K), plus the digit theorem module.
usage: gen_fast_prefix.py K"""
import sys
K = int(sys.argv[1]); A = 0; CH = 100; B = A + CH * K; tag = f"BBPFastCerts{B-1}"
L = [f"/-\n  GENERATED by `lean_tools/gen_fast_prefix.py {K}`; do not edit.\n\n  `bbpGuardAgrees_of_lt_{B}` : `∀ n < {B}, bbpGuardAgrees n`.\n  every n < {B} is checked by `BBPFastCerts10000Part0..{K-1}` (residue-form check, `BBPFastGuard.lean`).\n-/",
     ]
L += [f"import Thoughts.Proved.BBPFastCerts10000Part{i}" for i in range(K)]
L += ["", "namespace FinitistProved", "", f"theorem bbpGuardAgrees_of_lt_{B} : ∀ n < {B}, bbpGuardAgrees n := by", "  intro n hn"]
for i in range(K):
    a = A + CH * i; b = a + CH
    L += [f"  by_cases h{i} : n < {b}", f"  · exact bbpGuardAgrees_range_{a}_{b} n (by omega) h{i}"]
L += ["  omega", "", "end FinitistProved", ""]
open(f"Thoughts/Proved/{tag}.lean", "w").write("\n".join(L))
D = B - 1
open(f"Thoughts/Proved/BBPDigitsUnconditionalExt{D}.lean", "w").write(f"""/-
  P-BBP-01 (literal capped form, `BBPSpigotDigitCorrect`) unconditionally for every `n ≤ {D}`
  (generated by `lean_tools/gen_fast_prefix.py {K}`). Check: `BBPFastGuard.lean` + `BBPFastCerts10000Part0..{K-1}`.
  The bound is a compute-budget choice, not a mathematical limit. NOT proved: `PBBP01General` (all `n`);
  see `Thoughts/Research/BBPCapAnalysis.lean`, `docs/PBBP01_CAP_ANALYSIS_2026-10-28.md`.
-/
import Thoughts.Proved.BBPPiIdentity
import Thoughts.Proved.BBPGuarded
import Thoughts.Proved.BBPSpigot
import Thoughts.Proved.BBPDigitsUnconditional
import Thoughts.Proved.{tag}

namespace FinitistProved

theorem BBPSpigotDigitCorrect_of_le_{D}_unconditional (n : ℕ) (hn : n ≤ {D}) :
    BBPSpigotDigitCorrect n :=
  BBPSpigotDigitCorrect_of_guard bbpPiEqualsSeries_proved n (bbpGuardAgrees_of_lt_{B} n (by omega))

end FinitistProved

#print axioms FinitistProved.BBPSpigotDigitCorrect_of_le_{D}_unconditional
""")
print(tag, B)
